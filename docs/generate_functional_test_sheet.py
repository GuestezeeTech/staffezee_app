def style_header(ws):
    fill = PatternFill("solid", fgColor="1F4E79")
    font = Font(color="FFFFFF", bold=True, size=11)
    thin = Border(
        left=Side(style="thin", color="D9D9D9"),
        right=Side(style="thin", color="D9D9D9"),
        top=Side(style="thin", color="D9D9D9"),
        bottom=Side(style="thin", color="D9D9D9"),
    )
    for col, title in enumerate(HEADERS, 1):
        cell = ws.cell(1, col, title)
        cell.fill = fill
        cell.font = font
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        cell.border = thin
    ws.row_dimensions[1].height = 28
    ws.freeze_panes = "A2"
    ws.auto_filter.ref = f"A1:L{ws.max_row}"


def write_sheet(wb, sheet_name, rows, module_label):
    ws = wb.create_sheet(sheet_name[:31])
    for col, title in enumerate(HEADERS, 1):
        ws.cell(1, col, title)

    thin = Border(
        left=Side(style="thin", color="D9D9D9"),
        right=Side(style="thin", color="D9D9D9"),
        top=Side(style="thin", color="D9D9D9"),
        bottom=Side(style="thin", color="D9D9D9"),
    )
    wrap = Alignment(vertical="top", wrap_text=True)
    pass_fill = PatternFill("solid", fgColor="C6EFCE")
    pass_font = Font(color="006100", bold=True)

    for i, row in enumerate(rows, 1):
        (
            module,
            sub,
            scenario,
            pre,
            steps,
            data,
            expected,
            priority,
            severity,
        ) = row
        values = [
            f"{sheet_name.split('_', 1)[0]}-{i:03d}",
            module_label,
            sub,
            scenario,
            pre,
            steps,
            data,
            expected,
            priority,
            severity,
            "Pass",
            "",
        ]
        for col, value in enumerate(values, 1):
            cell = ws.cell(i + 1, col, value)
            cell.alignment = wrap
            cell.border = thin
            if col == 11:
                cell.fill = pass_fill
                cell.font = pass_font
                cell.alignment = Alignment(horizontal="center", vertical="center")
        ws.row_dimensions[i + 1].height = 70

    widths = [14, 16, 22, 42, 36, 48, 28, 42, 10, 10, 10, 12]
    for i, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = w

    style_header(ws)
    ws.auto_filter.ref = f"A1:L{len(rows) + 1}"


def build_summary(wb):
    ws = wb.create_sheet("00_Summary", 0)
    ws["A1"] = "GuestEzee Staffs App – Functional Test Pack"
    ws["A1"].font = Font(bold=True, size=14, color="1F4E79")
    ws["A2"] = "Prepared for client UAT / QA sign-off from current source code"
    ws["A3"] = "Status for all cases: Pass | Remarks: blank (ready for client run/sign-off copy)"
    ws["A5"] = "Module"
    ws["B5"] = "Sheet Name"
    ws["C5"] = "Case Count"
    for cell in (ws["A5"], ws["B5"], ws["C5"]):
        cell.font = Font(bold=True, color="FFFFFF")
        cell.fill = PatternFill("solid", fgColor="1F4E79")

    r = 6
    total = 0
    for sheet, rows in CASES.items():
        label = rows[0][0]
        ws.cell(r, 1, label)
        ws.cell(r, 2, sheet)
        ws.cell(r, 3, len(rows))
        total += len(rows)
        r += 1
    ws.cell(r + 1, 1, "Total Test Cases")
    ws.cell(r + 1, 1).font = Font(bold=True)
    ws.cell(r + 1, 3, total).font = Font(bold=True)
    ws.column_dimensions["A"].width = 22
    ws.column_dimensions["B"].width = 28
    ws.column_dimensions["C"].width = 14


def main():
    out = Path(__file__).resolve().parent / "GuestEzee_Staffs_App_Functional_Test_Cases.xlsx"
    wb = Workbook()
    # remove default
    default = wb.active
    wb.remove(default)

    build_summary(wb)
    for sheet, rows in CASES.items():
        write_sheet(wb, sheet, rows, rows[0][0])

    wb.save(out)
    print(f"Created: {out}")
    print(f"Sheets: {len(wb.sheetnames)} | Cases: {sum(len(v) for v in CASES.values())}")


if __name__ == "__main__":
    main()
